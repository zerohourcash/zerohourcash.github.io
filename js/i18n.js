  const supported = ["en", "ru"];

  function applyLang(lang) {
    const t = i18n[lang] || i18n.en;
    document.querySelectorAll("[data-i18n]").forEach((el) => {
      const key = el.getAttribute("data-i18n");
      const value = t[key];
      if (value === undefined) return;
      if (value.includes("<") && value.includes(">")) {
        el.innerHTML = value;
      } else {
        el.textContent = value;
      }
    });

    document.documentElement.lang = lang === "zh" ? "zh-CN" : lang;
    try { localStorage.setItem("zh.cash.lang", lang); } catch (_) {}

    const currentName = document.querySelector(".lang-current .lang-name");
    if (currentName) currentName.textContent = t["lang.current"] || (lang === "ru" ? "Русский" : "English");
  }

  function init() {
    let saved; try { saved = localStorage.getItem("zh.cash.lang"); } catch (_) {}
    const browser = navigator.language.slice(0, 2);
    const lang = supported.includes(saved) ? saved : (browser === "ru" ? "ru" : "en");
    applyLang(lang);

    const switcher = document.querySelector(".lang-switcher");
    if (!switcher) return;

    const current = switcher.querySelector(".lang-current");
    const options = switcher.querySelector(".lang-options");

    function toggle(open) {
      if (options) options.hidden = !open;
      if (current) current.setAttribute("aria-expanded", String(open));
    }

    if (current) {
      current.addEventListener("click", (e) => {
        e.stopPropagation();
        const isOpen = options ? options.hidden : false;
        toggle(isOpen);
      });
    }

    options?.querySelectorAll("li[data-lang]").forEach((li) => {
      li.addEventListener("click", () => {
        const lang = li.getAttribute("data-lang");
        if (lang) applyLang(lang);
        toggle(false);
      });
    });

    document.addEventListener("click", () => toggle(false));
  }

  if (document.readyState === "loading") {
    document.addEventListener("DOMContentLoaded", init);
  } else {
    init();
  }
